// Bundled generic sport-photo fallback library (0.11.12, Live TV Artwork Enrichment 2.0).
//
// Every image is real photography sourced from Wikimedia Commons with its licence
// verified via the Commons API (extmetadata: LicenseShortName / LicenseUrl / Artist)
// at sourcing time. Files are 1600px-wide JPEG renditions of the Commons originals,
// bundled under public/art/sports/ and served as static assets (same pattern as the
// existing public/art/ images, referenced by absolute /art/... paths).
//
// Licence notes:
// - CC BY / CC BY-SA entries carry the exact licence deed URL from extmetadata and
//   are attributed in Settings > App & Updates > Licenses and attribution, which
//   renders from this manifest so the credits can never drift from the bundle.
// - Public-domain entries carry no deed URL in extmetadata (Copyrighted: false,
//   AttributionRequired: false); their licenceUrl points at the Creative Commons
//   Public Domain Mark deed, and the Commons file page (sourcePage) carries the
//   full public-domain rationale. They are credited anyway, as a courtesy.
// - If a sport has no entry here it ships WITHOUT a photo fallback (channel
//   branding / placeholder instead). Never add an entry whose licence was not
//   verified through the Commons API.

