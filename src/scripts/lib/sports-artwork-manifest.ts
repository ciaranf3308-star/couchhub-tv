// Bundled generic sport-photo fallback library (0.11.12, Live TV Artwork Enrichment 2.0).
//
// Every image is real photography sourced from Wikimedia Commons with its licence
// verified via the Commons API (extmetadata: LicenseShortName / LicenseUrl / Artist)
// at sourcing time. Files are 1600px-wide JPEG renditions of the Commons originals,
// bundled under public/art/sports/ and served as static assets (same pattern as the
// existing public/art/ images, referenced by absolute /art/... paths).
//
// Licence notes:
// - CC BY / CC BY-SA entries carry the exact licence deed URL from extmetadata and
//   are attributed in Settings > App & Updates > Licenses and attribution, which
//   renders from this manifest so the credits can never drift from the bundle.
// - Public-domain entries carry no deed URL in extmetadata (Copyrighted: false,
//   AttributionRequired: false); their licenceUrl points at the Creative Commons
//   Public Domain Mark deed, and the Commons file page (sourcePage) carries the
//   full public-domain rationale. They are credited anyway, as a courtesy.
// - If a sport has no entry here it ships WITHOUT a photo fallback (channel
//   branding / placeholder instead). Never add an entry whose licence was not
//   verified through the Commons API.
// - 0.11.12 W5: entries may carry `subjects` (see SportsArtworkEntry) so
//   hierarchy level 3 can serve a team/venue photograph for a fixture
//   naming that team or competition. Subjects never change the level-4
//   generic fallback, which still draws from all entries of the sport.

// SportId mirrors the classifier contract (W1). Kept unexported: this module
// exports exactly SPORT_ARTWORK_MANIFEST and SportsArtworkEntry per the brief.
type SportId =
  "football"
  | "ice-hockey"
  | "snooker"
  | "rugby"
  | "motorsport"
  | "darts"
  | "tennis"
  | "golf"
  | "cricket"
  | "basketball"
  | "american-football"
  | "baseball"
  | "boxing"
  | "mma"
  | "cycling"
  | "athletics"
  | "other-sport"

export interface SportsArtworkEntry {
  sport: SportId
  path: string
  orientation: "landscape" | "portrait" | "square"
  width: number
  height: number
  creator: string
  sourcePage: string
  licence: string
  licenceUrl: string
  attribution: string
  /** 0.11.12 W5: normalised match keys for the team / venue /
   *  competition genuinely depicted by this photo (lowercase, no
   *  punctuation, e.g. "manchester united", "old trafford"). Only
   *  entries with subjects can match hierarchy level 3 (team/venue);
   *  entries without subjects stay generic-fallback-only. A key must
   *  name something the photo actually depicts — never re-tag a photo
   *  to a subject it does not show. */
  subjects?: string[]
}

